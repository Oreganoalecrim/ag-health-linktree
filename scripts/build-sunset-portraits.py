"""Generate full-frame, sunset-graded portrait variants from the owned photo.

Usage: python3 scripts/build-sunset-portraits.py ORIGINAL_PHOTO PERSON_MASK

PERSON_MASK is generated by Apple's Vision person-segmentation API.  No
geometric crop, AI face reconstruction, facial retouching, or third-party
photo request is performed. Keep the original private.
"""

from pathlib import Path
import sys

from PIL import Image, ImageChops, ImageDraw, ImageEnhance, ImageFilter


def tint(base: Image.Image) -> Image.Image:
    base = ImageEnhance.Color(base.convert("RGB")).enhance(1.13)
    base = ImageEnhance.Contrast(base).enhance(1.065)

    # Luminous amber highlight with cooler lilac shadows, as at golden hour.
    amber = Image.new("RGB", base.size, (254, 161, 111))
    base = Image.blend(base, amber, 0.105)
    shadows = ImageChops.invert(base.convert("L")).point(lambda v: round(v * 0.17))
    base.paste(Image.new("RGB", base.size, (120, 76, 142)), mask=shadows)

    # Broad sunset source grazing the left side of the face and shoulder.
    warm_light = Image.new("L", base.size, 0)
    draw = ImageDraw.Draw(warm_light)
    w, h = base.size
    draw.ellipse((-int(.55*w), int(.02*h), int(.78*w), int(.98*h)), fill=90)
    warm_light = warm_light.filter(ImageFilter.GaussianBlur(int(w * .21)))
    base.paste(Image.new("RGB", base.size, (255, 176, 118)), mask=warm_light)
    return base


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("Usage: build-sunset-portraits.py SOURCE.jpg MASK.png")
    original = Image.open(sys.argv[1]).convert("RGB")
    mask = Image.open(sys.argv[2]).convert("L")
    if original.size != mask.size:
        raise SystemExit("Original and person mask sizes must match")
    alpha = mask.filter(ImageFilter.GaussianBlur(1.1)).point(
        lambda v: 0 if v < 7 else (255 if v > 249 else v)
    )
    portrait = tint(original).convert("RGBA")
    portrait.putalpha(alpha)

    output = Path(__file__).resolve().parent.parent / "assets"
    output.mkdir(parents=True, exist_ok=True)
    for name, width in (("portrait.webp", 1100), ("portrait-tablet.webp", 900), ("portrait-mobile.webp", 760)):
        height = round(width * original.height / original.width)
        image = portrait.resize((width, height), Image.Resampling.LANCZOS)
        image.save(output / name, "WEBP", quality=86, method=6)
        print(name, image.size, (output / name).stat().st_size)


if __name__ == "__main__":
    main()
